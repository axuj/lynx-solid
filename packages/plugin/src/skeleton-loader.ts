/**
 * skeleton-loader — compiles ALL modules through the fork dom pipeline
 * (compileDomModule), producing the BG module code that
 * registers templates + instance refs instead of building trees.
 *
 * There is exactly one JSX compiler in this repo — every module (entry or
 * component) goes through the same fork dom path. The MT-side skeleton
 * module itself is emitted by VirtualSkeletonPlugin (index.ts) as an
 * in-memory module per beforeCompile; this loader never touches the disk.
 */

import type { LynxExtractedTemplate } from '@lynx-solid/compiler'
import type { LoaderContext } from '@rspack/core'
import { compileDomModuleCached } from '@lynx-solid/compiler'

/**
 * Render the MT-side skeleton module for the fork pipeline: one
 * `registerSkeleton(id, create)` call per template, via direct static
 * import (NOT a bare-global call: import hoisting guarantees the registry
 * evaluates first, while a late-installed global silently no-ops and
 * renders nothing). Same 2-arg shape as the entry-inline registrations
 * from `worklet-mt-loader.ts`. Worklet registrations are NOT emitted
 * here — they come from the worklet-mt-loader per module.
 */
export function renderSkeletonModuleLynx(
  templates: LynxExtractedTemplate[],
  registryModule: string,
): string {
  const lines = [
    '// @ts-nocheck',
    '// Generated by pluginSolidLynx — do not edit.',
    `import { registerSkeleton } from ${JSON.stringify(registryModule)}`,
    '',
  ]
  for (const t of templates) {
    // Trailing `;` is load-bearing: without it, consecutive registrations
    // parse as one continued call `register(...)(...)` and throw
    // `... is not a function` on multi-template entries (single-template
    // files survive via ASI, which hid this on web).
    lines.push(
      `registerSkeleton(${t.id}, ${t.createCode});`,
    )
  }
  return `${lines.join('\n')}\n`
}

export default function skeletonLoader(
  this: LoaderContext,
  source: string,
): string {
  return compileDomModuleCached(source, {
    filename: this.resourcePath,
  }).code
}
